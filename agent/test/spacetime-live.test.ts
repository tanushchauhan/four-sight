import assert from 'node:assert/strict';
import { test } from 'node:test';
import jpeg from 'jpeg-js';
import { loadConfig, loadEnvFile } from '../src/config.js';
import { SpacetimeState } from '../src/adapters/spacetime-state.js';
import { DamageService } from '../src/damage/service.js';
import { SimRobot } from '../src/adapters/sim-robot.js';
import { SpacetimeIncidentStore } from '../src/damage/storage.js';
import { OperatorVoice } from '../src/operator/voice.js';
import { SharedService } from '../src/shared/service.js';

test('live SpacetimeDB: rescue rules, atomic evidence, reviews, settings, feed history, and authorization', {skip:!process.env.SPACETIME_TEST_DB}, async t=>{
  loadEnvFile();
  const config=loadConfig({...process.env,STATE_MODE:'spacetime',SPACETIME_DB:process.env.SPACETIME_TEST_DB});
  const db=new SpacetimeState(config.spacetimeUrl,config.spacetimeDb,config.spacetimeToken,config.searchArea);
  const robot=new SimRobot();const snapshot=robot.takeSnapshot.bind(robot);
  const photo=jpeg.encode({width:2,height:2,data:Buffer.alloc(16,180)},70).data;
  robot.takeSnapshot=async()=>({...await snapshot(),takenAt:Date.now(),imageBase64:photo.toString('base64'),mimeType:'image/jpeg'});
  const damage=new DamageService(robot,config,{analyze:async()=>({incident:true,title:'Integration-test evidence',category:'water',severity:'unknown',confidence:.75,observations:['Test image, not real damage.'],uncertainties:['Synthetic test fixture.']})});
  t.after(()=>damage.stop());await damage.initialize();
  const survey='Integration '+Date.now();
  await damage.configure({survey,location:'Test only',enabled:false});
  const record=(await damage.capture()).record!;assert.ok(record.id);
  const store=new SpacetimeIncidentStore(db);
  assert.deepEqual(await store.photo(record.id),photo);
  assert.equal((await damage.capture()).duplicate,true);
  await damage.review(record.id,'Verified integration fixture');
  const restarted=new DamageService(robot,config);
  await restarted.initialize();
  assert.equal(restarted.status().survey,survey);assert.equal(restarted.status().enabled,false);
  const restored=(await restarted.list()).find(r=>r.id===record.id)!;assert.equal(restored.status,'reviewed');assert.equal(restored.reviewNote,'Verified integration fixture');
  assert.ok((await restarted.report([restored])).includes(photo.toString('base64')));
  const point=100+(await db.getCases()).length*10;
  await db.robotCheckin({id:9,name:'Test robot',mode:'searching',x:point,y:point,heading:0,battery:.8,pan:0,tilt:0,lastSeen:Date.now()});
  const c=await db.reportDetection(9,point,point,.9,'test-'+Date.now());assert.ok(c);
  await db.setTriage(c.id,'yellow','Integration fixture');assert.equal((await db.getCases()).find(r=>r.id===c.id)!.triage,'yellow');
  const confirmation=await db.requestConfirmation('Test approval',JSON.stringify({fixture:Date.now()}));
  await db.resolveConfirmation(confirmation,true);assert.equal((await db.getConfirmation(confirmation))!.status,'approved');
  const voice=new OperatorVoice({setTimer:false});
  await db.call('append_operator_update',[JSON.stringify({id:999,text:'Persisted test update',level:'info',time:Date.now(),interrupt:false})]);
  const shared=new SharedService(db,'http://127.0.0.1:1');await shared.initialize(voice);t.after(()=>shared.stop());
  assert.ok(voice.recent().some(u=>u.text==='Persisted test update'));
  assert.ok(voice.push({text:'Next update',level:'critical'})!.id>999);
  const anonymous=new SpacetimeState(config.spacetimeUrl,config.spacetimeDb,'',config.searchArea);
  await assert.rejects(anonymous.call('save_shared_state',['dashboard','{}']),/Service identity required|401|403/);
  const original=await db.sql(`SELECT id FROM damage_incident`);assert.ok(original.some(r=>r.id===record.id));
  console.log('Verified durable fixture in isolated database:',config.spacetimeDb,record.id);
});
